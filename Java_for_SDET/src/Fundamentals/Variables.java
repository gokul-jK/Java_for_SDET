package Fundamentals;

public class Variables {

	public static void main(String[] args) {
		// Declaration of Variable : <data type> <variable name>
		int number;
		
		//Initialization of variable : <variable name> = <value>
		number = 10;
		
		//Declaration and Initialization of variables: <data type> <variable name> = <value>
		
		String language = "Java";
		
		System.out.println(language + " is " + number);

	}

}
